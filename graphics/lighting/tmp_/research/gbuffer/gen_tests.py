def sqf_list(items):
    return "[" + ", ".join('"%s"' % s for s in items) + "]"


def view_block(view, modes):
    v = VIEWS[view]
    out = ["", "// ---- %s" % view, "%s call capBegin" % v["args"], "call {"]
    out += ["    " + p for p in v["props"]]
    out += ["}", "triSimFrames 150"]
    for label, base, knobs, settle in modes:
        shot = "%s__%s" % (view, label)
        out.append('["%s", "%s", %s] call capModeX' % (label, base, sqf_list(knobs)))
        out.append("triSimFrames %d" % settle)
        out.append("[] call capReadTimers")
        out.append("[] call capPin")
        if view == "town_night":
            out.append("call { if (not (isNull capFire)) then { capFire inflame true } }")
        out.append("triSimFrames 3")
        out.append('triScreenshot "%s"' % shot)
        out.append('"%s" call capRecord' % shot)
    out.append("[] call capClear")
    return "\n".join(out) + "\n"


def timing_block(view, modes, rounds):
    """Interleaved timing: every mode once per round, no screenshots."""
    v = VIEWS[view]
    out = ["", "// ---- timing %s" % view, "%s call capBegin" % v["args"], "call {"]
    out += ["    " + p for p in v["props"]]
    out += ["}", "triSimFrames 150"]
    for r in range(rounds):
        for label, base, knobs, settle in modes:
            shot = "%s__t%d_%s" % (view, r, label)
            out.append('["t%d_%s", "%s", %s] call capModeX' % (r, label, base, sqf_list(knobs)))
            out.append("triSimFrames %d" % settle)
            out.append("[] call capReadTimers")
            out.append('"%s" call capRecord' % shot)
    out.append("[] call capClear")
    return "\n".join(out) + "\n"


def write_test(name, world, probe, toml, blocks):
    px, pz = probe
    sqf = HEADER.format(world=world, px=px, pz=pz) + "".join(blocks)
    sqf += '\ncall { "view=done;event=done" call capLog }\ntriEndTest\n'
    with open(os.path.join(OUT, name + ".test.sqf"), "w", newline="\n") as f:
        f.write(sqf)
    with open(os.path.join(OUT, name + ".test.toml"), "w", newline="\n") as f:
        f.write(toml)
    print("wrote", name, len(blocks), "views")


