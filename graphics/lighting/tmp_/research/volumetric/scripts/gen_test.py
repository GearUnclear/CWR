FIRE = 'call { if (not (isNull capFire)) then { capFire inflame true } }\n'


def shot(view, label, mode, knobs, settle=60, fire=False, timers=True):
    out = []
    out.append('"%s" call capMode\n' % mode)
    out.append('call { capModeName = "%s" }\n' % label)
    if mode == 'remastered':
        out.append('capVolOff call capKnobs\n')
        if knobs:
            out.append('[%s] call capKnobs\n' % ', '.join('"%s"' % k for k in knobs))
        out.append('call { capGpuOff = triGpuTimes false; capGpuOn = triGpuTimes true; capPerfRes = triPerfReset 0 }\n')
    out.append('triSimFrames %d\n' % settle)
    out.append('[] call capReadTimers\n')
    out.append('[] call capPin\n')
    if fire:
        out.append(FIRE)
    out.append('triSimFrames 3\n')
    out.append('triScreenshot "%s__%s"\n' % (view, label))
    out.append('"%s__%s" call capRecord\n' % (view, label))
    return ''.join(out)


def pan(view, label, knobs, steps, every, deg):
    # A camera pan: settle on the view, then turn deg per frame for steps
    # frames, a shot every `every` frames (mid-motion), then restore the heading.
    out = [shot(view, '%s_p00' % label, 'remastered', knobs)]
    for k in range(1, steps + 1):
        out.append('call { capH = capH + %s; [] call capPinView }\n' % deg)
        out.append('triSimFrames 1\n')
        if k % every == 0:
            out.append('triScreenshot "%s__%s_p%02d"\n' % (view, label, k))
            out.append('"%s__%s_p%02d" call capRecord\n' % (view, label, k))
    out.append('call { capH = capH - %s; [] call capPin }\n' % round(deg * steps, 4))
    return ''.join(out)


def view_block(v):
    out = ['\n// ---- %s\n' % v['id']]
    out.append('["%s", %s, %s, %s, %s, %s, %s, %s, %s, %s] call capBegin\n' % (
        v['id'], v['x'], v['z'], v['eye'], v['h'], v['p'], v['date'], v.get('oc', 0), v.get('fog', 0), v.get('vd', 1500)))
    if v.get('fire'):
        out.append('call {\n    capFire = [["Fire"], 9, 3, 0, "veh"] call capSpawn;\n'
                   '    if (not (isNull capFire)) then { capFire inflame true };\n}\n')
    for sp in v.get('spawn', []):
        out.append('call { %s call capSpawn }\n' % sp)
    for raw in v.get('raw', []):
        out.append(raw + '\n')
    out.append('triSimFrames %d\n' % v.get('pre', 150))
    fire = bool(v.get('fire'))
    if v.get('classic', True):
        out.append(shot(v['id'], 'classic', 'classic', [], fire=fire))
    if v.get('current', True):
        out.append(shot(v['id'], 'remastered', 'remastered', [], fire=fire))
    for label, knobs in v['variants']:
        out.append(shot(v['id'], label, 'remastered', knobs, fire=fire))
    for label, knobs, steps, every, deg in v.get('pans', []):
        out.append(pan(v['id'], label, knobs, steps, every, deg))
    for raw in v.get('cleanup', []):
        out.append(raw + '\n')
    out.append('[] call capClear\ncall { capFire = objNull }\n')
    return ''.join(out)


