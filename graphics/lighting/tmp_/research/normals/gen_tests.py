def view_block(view, variants, settle, debug, debug_sat="21.12", debug_view=3):
    out = []
    if view == "tank_gunner_interior":
        out.append(TANK)
    else:
        world, begin, spawn = VIEWS[view]
        out.append(f"\n// ---- {view}\n{begin} call capBegin\ncall {{{spawn}\n}}\ntriSimFrames 150\n")
    out.append('"classic" call capMode\n')
    out.append(SHOT.format(settle=settle, view=view, label="classic"))
    out.append('"remastered" call capMode\n[] call capResetKnobs\n')
    out.append(SHOT.format(settle=settle, view=view, label="remastered"))
    for label, sat in variants:
        out.append(f'["{label}", "saturation={sat}"] call capVariant\n')
        out.append(SHOT.format(settle=settle, view=view, label=label))
    if debug:
        # Normals debug view with the strongest texture variant: shows the frame.
        out.append(f'["dbgn", "saturation={debug_sat}"] call capVariant\ncall {{ capLitD = triSetLighting "debug={debug_view}" }}\n')
        out.append(SHOT.format(settle=20, view=view, label="dbgnormal" if debug_view == 3 else f"dbgview{debug_view}"))
    out.append("[] call capResetKnobs\n")
    if view != "tank_gunner_interior":
        out.append("[] call capClear\n")
    return "".join(out)


def write_test(name, world, views, variants, settle, debug, debug_sat="21.12", debug_view=3):
    ox, oz = {"Abel": (7300, 10900), "Sinai": (8350, 2950)}[world]
    body = HEADER.format(world=world, ox=ox, oz=oz)
    # the tank view must come last (it moves the player into a vehicle)
    ordered = [v for v in views if v != "tank_gunner_interior"] + [v for v in views if v == "tank_gunner_interior"]
    for v in ordered:
        body += view_block(v, variants, settle, debug, debug_sat, debug_view)
    body += '\ncall { "view=done;event=done" call capLog }\ntriEndTest\n'
    (OUT / f"{name}.test.sqf").write_text(body, newline="\n")
    toml_src = COMMITTED / ("abel_lighting.test.toml" if world == "Abel" else "sinai_lobo_lighting.test.toml")
    toml = toml_src.read_text()
    toml = "# RESEARCH (normals track) copy of " + toml_src.name + "\n" + toml
    (OUT / f"{name}.test.toml").write_text(toml, newline="\n")
    return OUT / f"{name}.test.sqf"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tag")
    ap.add_argument("--variants", default="v1ss:11.12,v2tex:21.12,v3tex2x:31.12,v4nogate:41.12")
    ap.add_argument("--views", default="lowsun_fp,hull_close,noon_fields,forest_edge_golden,tank_gunner_interior,sinai_lowsun_fp,sinai_hull_close")
    ap.add_argument("--settle", type=int, default=90)
    ap.add_argument("--debug", action="store_true")
    ap.add_argument("--debug-sat", default="21.12", help="saturation knob for the normals debug shot")
    ap.add_argument("--debug-view", type=int, default=3, help="1 sun visibility, 2 sky visibility, 3 normals")
    a = ap.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    lib = (COMMITTED / "capture_lib.sqf").read_text() + LIB_EXTRA
    (OUT / "capture_lib.sqf").write_text(lib, newline="\n")
    variants = [tuple(x.split(":")) for x in a.variants.split(",") if x]
    views = a.views.split(",")
    abel = [v for v in views if v == "tank_gunner_interior" or VIEWS.get(v, ("",))[0] == "Abel"]
    sinai = [v for v in views if v != "tank_gunner_interior" and VIEWS.get(v, ("",))[0] == "Sinai"]
    made = []
    if abel:
        made.append(write_test(f"nrm_abel_{a.tag}", "Abel", abel, variants, a.settle, a.debug, a.debug_sat, a.debug_view))
    if sinai:
        made.append(write_test(f"nrm_sinai_{a.tag}", "Sinai", sinai, variants, a.settle, a.debug, a.debug_sat, a.debug_view))
    for m in made:
        print(m.relative_to(SCRATCH).as_posix())


if __name__ == "__main__":
    main()
