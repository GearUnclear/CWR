def write(name, world, mission, views, only=None, variants=None):
    if only:
        views = [v for v in views if v["id"] in only]
    if not views:
        return
    body = HEADER.format(world=world, ox=views[0]["ox"], oz=views[0]["oz"]) + "\n" + "\n".join(view_block(v, variants) for v in views)
    body += '\ncall { "view=done;event=done" call capLog }\ntriEndTest\n'
    (OUT / f"{name}.test.sqf").write_text(body, encoding="utf-8", newline="\n")
    (OUT / f"{name}.test.toml").write_text(TOML.format(m=mission), encoding="utf-8", newline="\n")
    print("wrote", name, [v["id"] for v in views])


