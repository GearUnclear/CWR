def sqf_list(items):
    return "[" + ", ".join('"%s"' % s for s in items) + "]"


def view_block(v, variants=None):
    variants = variants or VARIANTS
    vid = v["id"]
    lines = [f"// ---- {vid}: {v['note']}"]
    lines.append(f"[\"{vid}\", {v['ox']}, {v['oz']}, {v['eye']}, {v['heading']}, {v['pitch']}, {v['date']}, {v['overcast']}, 0, {v['vd']}] call capBegin")
    if v.get("props"):
        lines.append("call {")
        for p in v["props"]:
            lines.append(f"    {p} call capSpawn;")
        lines.append("}")
    lines.append("triSimFrames 150")
    # classic
    lines += [
        '"classic" call capMode',
        "triSimFrames 90",
        "[] call capReadTimers",
        "[] call capPin",
        "triSimFrames 3",
        f'triScreenshot "{vid}__classic"',
        f'"{vid}__classic" call capRecord',
    ]
    for label, settings, settle in variants:
        lines += [
            f'["{label}", {sqf_list(settings)}] call hfVariant',
            f"triSimFrames {settle}",
            "[] call capReadTimers",
            "[] call capPin",
            "triSimFrames 3",
            f'triScreenshot "{vid}__{label}"',
            f'"{vid}__{label}" call capRecord',
        ]
    lines.append("[] call capClear")
    lines.append("")
    return "\n".join(lines)


