def shot(view, label, settle=90, timers=True):
    s = f"triSimFrames {settle}\n"
    if timers:
        s += "[] call capReadTimers\n"
    s += f"[] call capPin\ntriSimFrames 3\ntriScreenshot \"{view}__{label}\"\n\"{view}__{label}\" call capRecord\n"
    return s


def view_block(view, begin, props, variants, debug):
    b = f"\n// ---------------------------------------------------------------- {view}\n{begin}\n{props}triSimFrames 150\n"
    b += '"classic" call capMode\n' + shot(view, "classic")
    b += '["remastered", []] call capVariant\n' + shot(view, "remastered")
    for label, knobs in variants:
        kl = ", ".join(f'"{k}"' for k in knobs)
        b += f'["{label}", [{kl}]] call capVariant\n' + shot(view, label)
    for label, knobs in debug:
        kl = ", ".join(f'"{k}"' for k in knobs)
        b += f'["{label}", [{kl}]] call capVariant\n' + shot(view, label, settle=10, timers=False)
    b += "[] call capClear\n"
    return b


def write(name, world, views, origin, variants, debug_by_view, mission):
    text = HEADER.format(world=world, px=origin[0], pz=origin[1])
    for v, (begin, props) in views.items():
        text += view_block(v, begin, props, variants, debug_by_view.get(v, []))
    text += '\ncall { "view=done;event=done" call capLog }\ntriEndTest\n'
    (OUT / f"{name}.test.sqf").write_text(text, encoding="ascii")
    (OUT / f"{name}.test.toml").write_text(
        "# GENERATED (atmosphere research track, not committed).\n"
        'binary = "PoseidonGame"\n'
        f'mission = "{mission}"\n'
        'tags = ["lighting_capture", "headful", "exclusive"]\n'
        "timeout = 900\nassert_timeout = 180\n"
        'extra_args = ["--no-strict", "--display-mode", "windowed", "--width", "960", "--height", "640"]\n',
        encoding="ascii")
    print("wrote", name)


def write_with_perf(name, world, views, origin, variants, debug_by_view, mission, perf_views, perf_knobs, reps=3):
    text = HEADER.format(world=world, px=origin[0], pz=origin[1])
    for v, (begin, props) in views.items():
        dbg = list(debug_by_view.get(v, []))
        text += view_block(v, begin, props, variants, dbg).replace("[] call capClear\n", "")
        if v in perf_views:
            kl = ", ".join(f'"{k}"' for k in perf_knobs)
            for i in range(1, reps + 1):
                text += f'["perfrem{i}", []] call capVariant\n' + shot(v, f"perfrem{i}", settle=120)
                text += f'["perfatmo{i}", [{kl}]] call capVariant\n' + shot(v, f"perfatmo{i}", settle=120)
        text += "[] call capClear\n"
    text += '\ncall { "view=done;event=done" call capLog }\ntriEndTest\n'
    (OUT / f"{name}.test.sqf").write_text(text, encoding="ascii")
    (OUT / f"{name}.test.toml").write_text(
        "# GENERATED (atmosphere research track, not committed).\n"
        'binary = "PoseidonGame"\n'
        f'mission = "{mission}"\n'
        'tags = ["lighting_capture", "headful", "exclusive"]\n'
        "timeout = 900\nassert_timeout = 180\n"
        'extra_args = ["--no-strict", "--display-mode", "windowed", "--width", "960", "--height", "640"]\n',
        encoding="ascii")
    print("wrote", name)


