"""Generate the haze research capture tests (research-only, git-excluded dir).

python gen_tests.py <out_dir> [--variants 0,1,2,...] [--suffix name] [--views a,b]
"""
import argparse
import os

ap = argparse.ArgumentParser()
ap.add_argument("out")
ap.add_argument("--variants", default="0,1,2,3,4,5")
ap.add_argument("--quick-variants", default="0,1,3,4")
ap.add_argument("--suffix", default="")
ap.add_argument("--views", default="")
ap.add_argument("--classic", type=int, default=1)
args = ap.parse_args()
full = [int(v) for v in args.variants.split(",") if v != ""]
quick = [int(v) for v in args.quick_variants.split(",") if v != ""]
only = set(v for v in args.views.split(",") if v)

HEADER = """// haze research capture run ({world}). Generated by gen_tests.py; research only.
#include "capture_lib.sqf"

triSimUntil {{ alive player }}

capWorld = "{world}"
capFov = 0.7
capSimT = 0
capPinTime = false
capUseView = false
capProps = []
capView = "setup"
capModeName = "none"
capLit = "none"
capGpu = "none"
capPerf = "none"

triCaptureAtPresent true
triSetMsaa 4
triSetRenderScale 1.5
showCinemaBorder false
enableRadio false
player setCaptive true
player allowDamage false

createCenter west
createCenter east
capGrpW = createGroup west
capProbe = "HeliHEmpty" createVehicle [{px}, {pz}, 0]
capCam = "camera" camCreate [{px}, {pz}, 2]
capCam cameraEffect ["internal", "back"]

triSimFrames 240
call {{ "view=setup;event=setup;world={world};msaa=4;scale=1.5;window=960x640;capture=present" call capLog }}
"""

SHOT = """{mode_stmt}
triSimFrames 90
[] call capReadTimers
[] call capPin
triSimFrames 3
triScreenshot "{view}__{label}"
"{view}__{label}" call capRecord
"""

VIEWS = {
    "abel": [
        ("sunrise_ridge", '["sunrise_ridge", 4400, 3300, 1.75, 60, 2, [1985, 7, 5, 5, 8], 0, 0, 4000] call capBegin', [], full),
        ("valley_morning", '["valley_morning", 6100, 5000, 1.75, 50, -6, [1985, 7, 5, 6, 30], 0, 0, 4000] call capBegin', [], full),
        ("dusk_valley", '["dusk_valley", 6100, 5000, 1.75, 285, 0, [1985, 7, 5, 18, 55], 0, 0, 4000] call capBegin', [], quick),
        ("noon_fields", '["noon_fields", 6250, 10800, 1.75, 150, -2, [1985, 7, 5, 12, 30], 0, 0, 2500] call capBegin',
         ['[["Jeep"], 13, 3, 60, "veh"] call capSpawn;', '[["SoldierWB"], 8, -2, 160, "man"] call capSpawn;'], quick),
    ],
    "eden": [
        ("overcast_broken", '["overcast_broken", 9200, 3700, 1.75, 288, -4, [1985, 7, 5, 14, 30], 0.5, 0, 3500] call capBegin',
         ['[["Jeep"], 12, -5, 70, "veh"] call capSpawn;'], quick),
    ],
}
PROBE = {"abel": (7300, 10900), "eden": (9200, 3700)}
TOML = """binary = "PoseidonGame"
mission = "tests/rendering/captures/missions/udcap_{world_l}.{world}"
tags = ["lighting_capture", "headful", "exclusive"]
timeout = 900
assert_timeout = 180
extra_args = ["--no-strict", "--display-mode", "windowed", "--width", "960", "--height", "640"]
"""

os.makedirs(args.out, exist_ok=True)
for world_l, views in VIEWS.items():
    views = [v for v in views if not only or v[0] in only]
    if not views:
        continue
    world = world_l.capitalize()
    px, pz = PROBE[world_l]
    s = HEADER.format(world=world, px=px, pz=pz)
    for view, begin, props, variants in views:
        s += f"\n// ---- {view}\n{begin}\n"
        if props:
            s += "call {\n" + "".join("    " + p + "\n" for p in props) + "}\n"
        s += "triSimFrames 150\n"
        if args.classic:
            s += SHOT.format(mode_stmt='"classic" call capMode', view=view, label="classic")
        for k in variants:
            s += SHOT.format(mode_stmt=f"{k} call capVar", view=view, label=f"haze_v{k}")
        s += "[] call capClear\n"
    s += '\ncall { capSat = triSetLighting "saturation=1.12" }\ncall { "view=end;event=done" call capLog }\ntriEndTest\n'
    name = f"haze_{world_l}{args.suffix}"
    with open(os.path.join(args.out, name + ".test.sqf"), "w", newline="\n") as f:
        f.write(s)
    with open(os.path.join(args.out, name + ".test.toml"), "w", newline="\n") as f:
        f.write(TOML.format(world_l=world_l, world=world))
    print("wrote", name)
