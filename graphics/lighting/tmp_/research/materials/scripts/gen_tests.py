def abel(name, variants, debug=(), views=('lowsun_fp', 'noon_fields', 'tank_gunner_optics'), settle=None):
    """Blocks are emitted in the order of `views`; settle = {view: extra frames after capBegin}."""
    L = header('Abel', 7300, 10900, 'Abel views')
    settle = settle or {}
    if isinstance(variants, dict):
        per = {v: [('classic', None), ('remastered', None)] + list(variants.get(v, [])) for v in views}
    else:
        per = {v: [('classic', None), ('remastered', None)] + list(variants) + list(debug) for v in views}
    pre = lambda v, extra=None: (['triSimFrames %d' % settle[v]] if v in settle else []) + (extra or [])
    blocks = {}
    if 'lowsun_fp' in views:
        blocks['lowsun_fp'] = block('lowsun_fp',
                   '["lowsun_fp", 7300, 10900, 1.75, 152.5, -3, [1985, 3, 1, 8, 0], 0, 0, 1500] call capBegin',
                   ['[["Jeep"], 10, -5, -107.5, "veh"] call capSpawn', '[["M113"], 16, 5, 72.5, "veh"] call capSpawn',
                    '[["SoldierWB"], 7, 1, -112.5, "man"] call capSpawn',
                    '[["LoBo_camnet", "CampEast", "Camp"], 22, -3, -152.5, "veh"] call capSpawn'], per['lowsun_fp'],
                   extra_pre=pre('lowsun_fp'))
    if 'noon_fields' in views:
        blocks['noon_fields'] = block('noon_fields',
                   '["noon_fields", 6250, 10800, 1.75, 150, -2, [1985, 7, 5, 12, 30], 0, 0, 2500] call capBegin',
                   ['[["Jeep"], 13, 3, 60, "veh"] call capSpawn', '[["SoldierWB"], 8, -2, 160, "man"] call capSpawn'],
                   per['noon_fields'], extra_pre=pre('noon_fields'))
    if 'abel_rain' in views:
        blocks['abel_rain'] = block('abel_rain',
                   '["abel_rain", 7300, 10900, 1.75, 152.5, -3, [1985, 3, 1, 10, 30], 0.9, 0, 1500] call capBegin',
                   ['[["Jeep"], 10, -5, -107.5, "veh"] call capSpawn', '[["M113"], 16, 5, 72.5, "veh"] call capSpawn',
                    '[["SoldierWB"], 7, 1, -112.5, "man"] call capSpawn',
                    '[["LoBo_camnet", "CampEast", "Camp"], 22, -3, -152.5, "veh"] call capSpawn'], per['abel_rain'],
                   extra_pre=pre('abel_rain'), rain=1)
    for tv, ovc, rain in (('town_night', 0, 0), ('town_night_rain', 0.9, 1)):
        if tv in views:
            fire = ['call { capFire = [["Fire"], 9, 3, 0, "veh"] call capSpawn; '
                    'if (not (isNull capFire)) then { capFire inflame true }; }']
            b = block(tv, '["%s", 7152, 8915, 1.75, 345, 3, [1985, 2, 27, 22, 0], %s, 0, 800] call capBegin' % (tv, ovc),
                      [], per[tv], extra_pre=pre(tv, fire), rain=rain)
            out = []
            for l in b:
                out.append(l)
                if l == '[] call capPin':
                    out.append('call { if (not (isNull capFire)) then { capFire inflame true } }')
            blocks[tv] = out
    if 'tank_gunner_optics' in views:
        tank = ['call {', '    capUseView = false;', '    capCam cameraEffect ["terminate", "back"];',
                '    capClearRes = triClearView;', '    capTankCls = ["M60", "M1Abrams", "T72"] call capPick;',
                '    capTank = objNull;',
                '    if (capTankCls != "") then { capTank = capTankCls createVehicle [7300, 10900, 0] };',
                '    if (not (isNull capTank)) then { capTank setDir 152.5; capTank setPos [7300, 10900, 0]; '
                'capTank allowDamage false; player moveInGunner capTank; };',
                '}', 'triSimFrames 60', 'call { (vehicle player) switchCamera "GUNNER" }', 'triSimFrames 60']
        blocks['tank_gunner_optics'] = block('tank_gunner_optics',
                   '["tank_gunner_optics", 7300, 10900, 1.75, 152.5, 0, [1985, 7, 5, 10, 0], 0, 0, 1500] call capBegin',
                   ['[["M113"], 70, 4, 90, "veh"] call capSpawn', '[["Jeep"], 55, -10, -60, "veh"] call capSpawn',
                    '[["SoldierWB"], 50, 0, 180, "man"] call capSpawn'], per['tank_gunner_optics'],
                   extra_pre=tank, clear=False)
    for v in views:
        L += blocks[v]
    write(name, L, ABEL_TOML)


def eden(name, variants, debug=()):
    L = header('Eden', 9200, 3700, 'Eden: overcast_heavy with rain falling')
    base = [('classic', None), ('remastered', None)] + list(variants) + list(debug)
    L += block('overcast_heavy_rain',
               '["overcast_heavy_rain", 9200, 3700, 1.75, 288, -4, [1985, 7, 5, 14, 30], 0.9, 0, 3500] call capBegin',
               ['[["Jeep"], 12, -5, 70, "veh"] call capSpawn', '[["SoldierWB"], 7, 1, 200, "man"] call capSpawn'],
               base, rain=1)
    write(name, L, EDEN_TOML)


