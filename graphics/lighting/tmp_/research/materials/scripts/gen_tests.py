MAT = ['materials=1']


def shot(view, label, knobs, timers=True):
    out = []
    if label == 'classic':
        out.append('"classic" call capMode')
    elif label == 'remastered':
        out.append('"remastered" call capMode')
        out.append('[] call capResetKnobs')
    else:
        ks = ', '.join('"%s"' % k for k in knobs)
        out.append('["%s", [%s]] call capVariant' % (label, ks))
    out.append('triSimFrames %d' % (90 if timers else 20))
    if timers:
        out.append('[] call capReadTimers')
    out.append('[] call capPin')
    out.append('triSimFrames 3')
    out.append('triScreenshot "%s__%s"' % (view, label))
    out.append('"%s__%s" call capRecord' % (view, label))
    return out


def block(view, begin, props, shots, extra_pre=None, clear=True, rain=0):
    out = ['', '// ---- %s' % view, 'capRain = %s' % rain, begin]
    if props:
        out.append('call {')
        out += ['    %s;' % p for p in props]
        out.append('}')
    if extra_pre:
        out += extra_pre
    out.append('triSimFrames 150')
    for s in shots:
        out += shot(view, *s)
    out.append('[] call capResetKnobs')
    if clear:
        out.append('[] call capClear')
    return out


def header(world, x, z, comment):
    return ['// RESEARCH (materials track): generated by gen_tests.py. ' + comment,
            '#include "capture_lib.sqf"', '', 'triSimUntil { alive player }', '',
            'capWorld = "%s"' % world, 'capFov = 0.7', 'capSimT = 0', 'capPinTime = false', 'capUseView = false',
            'capProps = []', 'capView = "setup"', 'capModeName = "none"', 'capLit = "none"', 'capGpu = "none"',
            'capPerf = "none"', 'triCaptureAtPresent true', 'triSetMsaa 4', 'triSetRenderScale 1.5',
            'showCinemaBorder false', 'enableRadio false', 'player setCaptive true', 'player allowDamage false',
            'createCenter west', 'createCenter east', 'capGrpW = createGroup west',
            'capProbe = "HeliHEmpty" createVehicle [%d, %d, 0]' % (x, z),
            'capCam = "camera" camCreate [%d, %d, 2]' % (x, z),
            'capCam cameraEffect ["internal", "back"]', 'triSimFrames 240',
            'call { "view=setup;event=setup;world=%s;research=materials" call capLog }' % world]


def write(name, lines, toml):
    body = lines + ['', 'call { "view=done;event=done" call capLog }', 'triEndTest', '']
    with open(os.path.join(R, name + '.test.sqf'), 'w', newline='\n') as f:
        f.write('\n'.join(body))
    with open(os.path.join(R, name + '.test.toml'), 'w', newline='\n') as f:
        f.write(toml)


