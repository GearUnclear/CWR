def view_ffn(lines, modes):
    """Moonless night firefight at eye height: volleys, a shell behind the lines."""
    lines.append('["ffn", 7600, 10850, 1.8, 0, -2, [1985, 7, 12, 23, 0], 0, 0, 1000] call capBegin')
    lines.append("capPinTime = false")
    lines.append(STAGE_N)
    for m in modes:
        lines.append("[] call capFFStageN")
        lines.append(mode_call(m))
        frames(lines, 150)
        lines.append("[] call capReadTimers")
        lines.append("call { [] call capPinEnv; [] call capPinView; [] call capBurn; if (not (isNull capFire)) then { capFire inflame true } }")
        frames(lines, 3)
        shot(lines, f"ffn_{m}_0")
        lines.append("(capFW + capFE) call capVolley")
        for i, n in enumerate([2, 2, 2, 3, 4]):
            frames(lines, n)
            shot(lines, f"ffn_{m}_v{'abcde'[i]}")
        frames(lines, 30)
        boom_seq(lines, "ffn", m, "[40, -6]")
        lines.append("[] call capClearAll")
        frames(lines, 30)


