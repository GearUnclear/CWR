VIEWS = {
    "ffh": lambda L, M: view_ffh(L, M or "crowx"),
    "ffn": lambda L, M: view_ffn(L, M or "crowx"),
    "ffd": lambda L, M: view_ffd(L, M or "crx"),
    "muz": lambda L, M: view_muz(L, M or "crx"),
    "camp": lambda L, M: view_camp(L, M or "crowx"),
    "cost": lambda L, M: view_cost(L),
    "flr": lambda L, M: view_flr(L, M or "crwx"),
    "campn": lambda L, M: view_campn(L, M or "crwx"),
    "ffday": lambda L, M: view_ffday(L, M or "crx"),
}


def main():
    global FLASH, FIRE
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--name", default="combat_r8")
    ap.add_argument("--views", default="ffh,ffn,ffd,muz,camp,cost", help="view[:modes],...")
    ap.add_argument("--flash", default=FLASH)
    ap.add_argument("--fire", default=FIRE)
    ap.add_argument("--lib", required=True)
    a = ap.parse_args()
    FLASH, FIRE = a.flash, a.fire
    os.makedirs(a.out, exist_ok=True)
    lines = [HEAD]
    for v in a.views.split(","):
        name, _, modes = v.partition(":")
        VIEWS[name](lines, modes)
    lines.append('call { "view=done;event=done" call capLog }')
    lines.append("triEndTest")
    with open(os.path.join(a.out, a.name + ".test.sqf"), "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(a.out, a.name + ".test.toml"), "w", newline="\n") as f:
        f.write(TOML)
    shutil.copyfile(a.lib, os.path.join(a.out, "capture_lib.sqf"))
    print("wrote", a.out, a.name)


if __name__ == "__main__":
    main()
