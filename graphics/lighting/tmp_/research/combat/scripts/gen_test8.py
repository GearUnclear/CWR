FLASH = "6"
FIRE = "2.5"
SMOKE = "0.6"


def knobs(m):
    base = "combatSmoke=1,combatScatter=1,combatWreck=1"
    base7 = f"combatSmoke={SMOKE},combatScatter=1,combatWreck=1"
    if m in ("c", "r"):
        return "combatLights=0," + base + ",combatShadow=0,combatFlash=1,combatFire=1"
    if m == "o":
        return "combatLights=1," + base + ",combatShadow=0,combatFlash=1,combatFire=1"
    if m == "w":
        return f"combatLights=1,{base7},combatShadow=0,combatFlash={FLASH},combatFire={FIRE}"
    if m == "s":
        return f"combatLights=1,{base},combatShadow=1,combatFlash={FLASH},combatFire={FIRE}"
    if m == "x":
        return f"combatLights=1,{base7},combatShadow=1,combatFlash={FLASH},combatFire={FIRE}"
    raise ValueError(m)


def mode_call(m):
    # triSetLighting takes one key=value per call: pass the knobs as an array.
    lit = "classic" if m == "c" else "remastered"
    arr = ", ".join(f'"{k}"' for k in knobs(m).split(","))
    return f'["{m}", [{arr}], "{lit}"] call capModeK'


