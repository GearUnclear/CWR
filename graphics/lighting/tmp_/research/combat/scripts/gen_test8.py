# frames after the shell is created; the shell lands after about 8 frames
BOOM_STEPS = [6, 1, 1, 1, 1, 1, 1, 2, 3, 5, 8, 15]


def shot(lines, label):
    lines.append(f'triScreenshot "{label}"')
    lines.append(f'"{label}" call capRecord')


def frames(lines, n):
    lines.append(f"triSimFrames {n}")


def boom_seq(lines, name, m, where):
    lines.append(f"{where} call capBoom")
    for i, n in enumerate(BOOM_STEPS):
        frames(lines, n)
        shot(lines, f"{name}_{m}_b{i + 1:02d}")


