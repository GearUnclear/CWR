"""Generates the round-8 combat-light research capture test (copy of
gen_test7.py with a day view and a longer cost alternation; the engine changes
of round 8 are in the C++: ordered shadow jitter, 24 steps, shorter fireball,
soft smoke saturation).

Round-7 notes (copy of
gen_test6.py: round 7 adds flares, a moonless campfire view, smoke gain 0.6 in
x and mode s = the round-6 x settings).

Original round-6 notes:

Round 6 adds the screen-space combat shadow, a brighter white-hot explosion
flash (combatFlash) and a stronger fire light (combatFire). Each mode is one
letter with an explicit knob string, so no knob leaks from one mode into the
next:

  c  Classic
  r  Remastered (current, combat lights off)
  o  combat lights as run 5 (flash 1, fire 1, no shadow)
  w  round 6 without the shadow (flash F, fire G, shadow 0)
  x  round 6 (flash F, fire G, shadow 1)

Every triScreenshot must be a top-level statement with a literal label, so the
shot lines are spelled out.
"""
import argparse
