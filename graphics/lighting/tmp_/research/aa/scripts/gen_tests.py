"""Generate the research capture tests for track aa (post AA, sharpening,
alpha coverage). Writes into arma_CWR/tests/rendering/research/aa/ (git-excluded).

Every view is shot at two AA settings in ONE game session:
  H = the capture default: 4x MSAA, 150% render scale (alpha-to-coverage on)
  D = the shipped GraphicsConfig default: no MSAA, 100% scale (plain alpha test)
and per setting: Classic, Remastered (current), and Remastered with the
research variants, chosen at runtime through two selector knobs that the
override shaders decode (see overrides/all/*.glsl):
  saturation = 1.12 + 0.001*j   world shaders, alpha coverage variant j
  ao         = 0.70 + 0.001*k   composite, AA / sharpening variant k
Optional pans: 4 frames, heading stepped by a sub-pixel 0.025 deg per frame,
sim clock re-pinned, for shimmer.
"""
import sys
from pathlib import Path

OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(
    r"D:\Arma_CWA_worktrees\lighting\arma_CWR\tests\rendering\research\aa")

# (label suffix, mode, j, k). v2 (scratch build): k = composite variant + 10 * present variant.
SET = "v2"
if SET == "v1":
    STILLS_H = [
        ("H-classic", "classic", 0, 0), ("H-rem", "remastered", 0, 0), ("H-cov1", "remastered", 1, 0),
        ("H-cov2", "remastered", 2, 0), ("H-cov4", "remastered", 4, 0), ("H-fxaa", "remastered", 0, 1),
        ("H-cas05", "remastered", 0, 2), ("H-cas10", "remastered", 0, 4), ("H-best", "remastered", 2, 3),
    ]
    STILLS_D = [
        ("D-classic", "classic", 0, 0), ("D-rem", "remastered", 0, 0), ("D-cov1", "remastered", 1, 0),
        ("D-cov3", "remastered", 3, 0), ("D-fxaa", "remastered", 0, 1), ("D-cas05", "remastered", 0, 2),
        ("D-best", "remastered", 1, 3),
    ]
    PANS_H = [("panH-rem", "remastered", 0, 0), ("panH-best", "remastered", 2, 3)]
    PANS_D = [("panD-rem", "remastered", 0, 0), ("panD-best", "remastered", 1, 3), ("panD-fxaa", "remastered", 0, 1)]
else:
    STILLS_H = [
        ("H-classic", "classic", 0, 0),
        ("H-rem", "remastered", 0, 0),
        ("H-cov2", "remastered", 2, 0),
        ("H-cov3", "remastered", 3, 0),
        ("H-lz", "remastered", 0, 10),
        ("H-lzrcas05", "remastered", 0, 20),
        ("H-lzrcas10", "remastered", 0, 40),
        ("H-blrcas05", "remastered", 0, 30),
        ("H-compcas10", "remastered", 0, 4),
        ("H-best2", "remastered", 2, 20),
        ("H-best3", "remastered", 3, 20),
    ]
    STILLS_D = [
        ("D-classic", "classic", 0, 0),
        ("D-rem", "remastered", 0, 0),
        ("D-cov1", "remastered", 1, 0),
        ("D-cov3", "remastered", 3, 0),
        ("D-fxaa", "remastered", 0, 1),
        ("D-rcas05", "remastered", 0, 20),
        ("D-best", "remastered", 3, 21),
    ]
    PANS_H = [("panH-rem", "remastered", 0, 0), ("panH-best3", "remastered", 3, 20)]
    PANS_D = [("panD-rem", "remastered", 0, 0), ("panD-best", "remastered", 3, 21), ("panD-cov3", "remastered", 3, 0)]
PAN_FRAMES = 4
PAN_STEP = 0.025

AA_LIB = r'''
// ---- research track aa helpers -------------------------------------------
// ["label", "classic"|"remastered", j, k] call aaSet: lighting model, the two
// selector knobs, then restart the GPU / CPU timers for this variant.
aaSet = {
    capModeName = _this select 0;
    capLit = triSetLighting (_this select 1);
    aaR1 = triSetLighting (format ["saturation=%1", 1.12 + 0.001 * (_this select 2)]);
    aaR2 = triSetLighting (format ["ao=%1", 0.7 + 0.001 * (_this select 3)]);
    capGpuOff = triGpuTimes false;
    capGpuOn = triGpuTimes true;
    capPerfRes = triPerfReset 0;
    format ["view=%1;event=mode;mode=%2;lit=%3;sat=%4;ao=%5;j=%6;k=%7", capView, capModeName, capLit, aaR1, aaR2, _this select 2, _this select 3] call capLog;
    true
}
// "H" | "D" call aaSetting
aaSetting = {
    if (_this == "H") then { aaM = triSetMsaa 4; aaS = triSetRenderScale 1.5 } else { aaM = triSetMsaa 0; aaS = triSetRenderScale 1.0 };
    format ["view=%1;event=setting;setting=%2;msaa=%3;scale=%4", capView, _this, aaM, aaS] call capLog;
    true
}
aaExtraPin = { true }
'''


def header(world, ox, oz, extra_toml_note=""):
    return f'''// Research track aa (post AA, sharpening, alpha coverage). Generated by
// tmp/research/aa/scripts/gen_tests.py; not a regression test.
#include "capture_lib.sqf"

triSimUntil {{ alive player }}

capWorld = "{world}"
capFov = 0.7
capSimT = 0
capPinTime = false
capUseView = false
capProps = []
capView = "setup"
capModeName = "none"
capLit = "none"
capGpu = "none"
capPerf = "none"
{AA_LIB}
triCaptureAtPresent true
triSetMsaa 4
triSetRenderScale 1.5
showCinemaBorder false
enableRadio false
player setCaptive true
player allowDamage false

createCenter west
createCenter east
capGrpW = createGroup west
capProbe = "HeliHEmpty" createVehicle [{ox}, {oz}, 0]
capCam = "camera" camCreate [{ox}, {oz}, 2]
capCam cameraEffect ["internal", "back"]

triSimFrames 240
call {{ "view=setup;event=setup;world={world};track=aa" call capLog }}
'''


def shot(view, label, mode, j, k):
    full = f"{view}__{label}"
    return f'''call {{ ["{label}", "{mode}", {j}, {k}] call aaSet }}
triSimFrames 90
[] call capReadTimers
[] call capPin
call {{ [] call aaExtraPin }}
triSimFrames 3
triScreenshot "{full}"
"{full}" call capRecord
'''


def pan(view, label, mode, j, k):
    s = f'''call {{ ["{label}", "{mode}", {j}, {k}] call aaSet }}
triSimFrames 60
'''
    for i in range(PAN_FRAMES):
        full = f"{view}__{label}-{i}"
        s += f'''call {{ capH = capH0 + {i * PAN_STEP:.3f}; true }}
[] call capPin
call {{ [] call aaExtraPin }}
triSimFrames 3
triScreenshot "{full}"
"{full}" call capRecord
'''
    s += "call { capH = capH0; true }\n"
    return s


def view_block(view, begin, props, extra_pin=None, pans=False):
    s = f'''
// ----------------------------------------------------------------------------
//  {view}
// ----------------------------------------------------------------------------
{begin} call capBegin
call {{ capH0 = capH; {props} true }}
'''
    if extra_pin:
        s += f"aaExtraPin = {{ {extra_pin}; true }}\n"
    else:
        s += "aaExtraPin = { true }\n"
    s += "triSimFrames 150\n"
    s += 'call { "H" call aaSetting }\ntriSimFrames 30\n'
    for lab, mode, j, k in STILLS_H:
        s += shot(view, lab, mode, j, k)
    if pans:
        for lab, mode, j, k in PANS_H:
            s += pan(view, lab, mode, j, k)
    s += 'call { "D" call aaSetting }\ntriSimFrames 30\n'
    for lab, mode, j, k in STILLS_D:
        s += shot(view, lab, mode, j, k)
    if pans:
        for lab, mode, j, k in PANS_D:
            s += pan(view, lab, mode, j, k)
    s += 'call { "H" call aaSetting }\ntriSimFrames 30\n[] call capClear\n'
    return s


def footer():
    return '\ncall { "view=done;event=done" call capLog }\ntriEndTest\n'


def toml(mission, timeout, extra):
    return f'''# Research track aa capture run (generated; not a regression test).
binary = "PoseidonGame"
mission = "{mission}"
tags = ["lighting_capture", "headful", "exclusive"]
timeout = {timeout}
assert_timeout = 240
extra_args = {extra}
'''


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    win = '"--display-mode", "windowed", "--width", "960", "--height", "640"'
    # Abel: forest_edge_golden (with pans) and town_night
    abel = header("Abel", 4674, 10156)
    abel += view_block("forest_edge_golden",
                       '["forest_edge_golden", 4674, 10156, 1.75, 75, 3, [1985, 7, 5, 18, 15], 0, 0, 1500]',
                       '[["SoldierWB"], 12, 2, 215, "man"] call capSpawn;', pans=True)
    abel += view_block("town_night",
                       '["town_night", 7152, 8915, 1.75, 345, 3, [1985, 2, 27, 22, 0], 0, 0, 800]',
                       'capFire = [["Fire"], 9, 3, 0, "veh"] call capSpawn; if (not (isNull capFire)) then { capFire inflame true };',
                       extra_pin='if (not (isNull capFire)) then { capFire inflame true }')
    abel += footer()
    (OUT / "aa_abel.test.sqf").write_text(abel, encoding="utf-8", newline="\n")
    (OUT / "aa_abel.test.toml").write_text(toml("tests/rendering/captures/missions/udcap_abel.Abel", 1500,
                                                f'["--no-strict", {win}]'), encoding="utf-8", newline="\n")
    # Eden: overcast_broken (with pans)
    eden = header("Eden", 9200, 3700)
    eden += view_block("overcast_broken",
                       '["overcast_broken", 9200, 3700, 1.75, 288, -4, [1985, 7, 5, 14, 30], 0.5, 0, 3500]',
                       '[["Jeep"], 12, -5, 70, "veh"] call capSpawn;', pans=True)
    eden += footer()
    (OUT / "aa_eden.test.sqf").write_text(eden, encoding="utf-8", newline="\n")
    (OUT / "aa_eden.test.toml").write_text(toml("tests/rendering/captures/missions/udcap_eden.Eden", 1200,
                                                f'["--no-strict", {win}]'), encoding="utf-8", newline="\n")
    # Sinai: sinai_lowsun_fp (the camouflage net)
    sinai = header("Sinai", 8350, 2950)
    sinai += view_block("sinai_lowsun_fp",
                        '["sinai_lowsun_fp", 8350, 2950, 1.75, 338.8, -3, [2005, 7, 21, 16, 10], 0, 0, 2000]',
                        '[["LoBoHMWV_Mag_Patrol", "Jeep"], 10, -5, -107.8, "veh"] call capSpawn; '
                        '[["LoBo_Zelda", "M113"], 16, 5, 72.2, "veh"] call capSpawn; '
                        '[["LoBoGolaniWB", "SoldierWB"], 7, 1, -112.8, "man"] call capSpawn; '
                        '[["LoBo_camnet", "CampEast", "Camp"], 22, -3, -152.8, "veh"] call capSpawn;')
    sinai += footer()
    (OUT / "aa_sinai.test.sqf").write_text(sinai, encoding="utf-8", newline="\n")
    (OUT / "aa_sinai.test.toml").write_text(toml("tests/rendering/captures/missions/udcap_sinai.Sinai", 1500,
                                                 f'["--no-strict", "--mods-dir", ".", "--mod", "@LoBo", {win}]'),
                                            encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
