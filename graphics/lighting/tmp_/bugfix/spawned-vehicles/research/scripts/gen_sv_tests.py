def write(name, world, probe, views, tank, toml, mission, prefix):
    body = HEADER.format(world=world, px=probe[0], pz=probe[1])
    for vid, begin, spawns in views:
        body += view_block(prefix + vid, begin, spawns)
    if tank:
        body += TANK.format(id=prefix + "tank_gunner_interior")
    else:
        body += 'call { "view=done;event=done" call capLog }\ntriEndTest\n'
    (OUT / f"{name}.test.sqf").write_text(body, newline="\n")
    (OUT / f"{name}.test.toml").write_text(toml.format(mission=mission), newline="\n")


