"""Generate the research capture tests for the spawned-vehicles bug fix.

Writes sv_abel / sv_abel_pre / sv_sinai / sv_sinai_pre (.test.sqf + .test.toml)
into <scratch>/arma_CWR/tests/rendering/research/spawned-vehicles/.
The *_pre tests boot a mission that PLACES the same classes far from every
view, so their shapes load before Shapes.OptimizeAll (the mission-placed
reference); the view ids get a "placed_" prefix so the labels stay unique.
"""
