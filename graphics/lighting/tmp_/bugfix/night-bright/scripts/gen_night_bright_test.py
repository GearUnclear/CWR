"""Research-only generator (git-excluded) for the night-bright bug captures.

python gen.py <name> <mode>[,<mode>...]
Writes <name>.test.sqf / .toml beside this file. Modes:
  classic, remastered, nolocal (localLights=0), nomoon (moonlight=0),
  sat1 (saturation=1), nosky (sky=0)
"""
import sys
from pathlib import Path

HERE = Path(__file__).parent

DEFAULTS = ["localLights=1", "moonlight=1", "saturation=1.12", "sky=1", "exposure=1", "bounce=1"]
MODES = {
    "classic": ["classic"] + DEFAULTS,
    "remastered": ["remastered"] + DEFAULTS,
    "nolocal": ["remastered"] + DEFAULTS + ["localLights=0"],
    "nomoon": ["remastered"] + DEFAULTS + ["moonlight=0"],
    "sat1": ["remastered"] + DEFAULTS + ["saturation=1"],
    "nosky": ["remastered"] + DEFAULTS + ["sky=0"],
    "moon06": ["remastered"] + DEFAULTS + ["moonlight=0.6"],
    "moon16": ["remastered"] + DEFAULTS + ["moonlight=1.6"],
    "ll075": ["remastered"] + DEFAULTS + ["localLights=0.75"],
    "ll060": ["remastered"] + DEFAULTS + ["localLights=0.6"],
    "ll045": ["remastered"] + DEFAULTS + ["localLights=0.45"],
}

JEEP = ('call { capJeep = [["Jeep"], %s, 0, 0, "veh"] call capSpawn; if (not (isNull capJeep)) then '
        '{ capJeep lock false; "SoldierWB" createUnit [[7250, 10950, 0], capGrpW, "capDrv = this", 0.6, "PRIVATE"]; '
        'capDrv setCaptive true; capDrv allowDamage false; capDrv moveInDriver capJeep; capDrv disableAI "MOVE"; '
        'capDrv setBehaviour "SAFE" }; format ["view=%%1;event=jeep;jeep=%%2;driver=%%3", capView, capJeep, '
        'driver capJeep] call capLog }')
FIRE = 'call { capFire = [["Fire"], 9, 3, 0, "veh"] call capSpawn; [] call capFireOn }'
NV_ON = 'call { player addWeapon "NVGoggles"; player action ["NVGOGGLES", player]; "view=nv_town;event=nv_on" call capLog }'
NV_OFF = 'call { player action ["NVGOGGLES", player]; "view=nv_town;event=nv_off" call capLog }'

# id, x, z, eye, heading, pitch, date, setup lines, teardown lines, modes override
VIEWS = [
    ("town_night", 7152, 8915, 1.75, 345, 3, "[1985, 2, 27, 22, 0]", [FIRE], [], None),
    ("town_lamps", 7152, 8915, 1.75, 352, 0, "[1985, 3, 17, 23, 0]", [], [], None),
    ("road_moonless", 6891.9, 8835.4, 3.0, 69.6, -6, "[1985, 3, 17, 23, 0]", [JEEP % "9"], [], None),
    ("road_moonlit", 6891.9, 8835.4, 3.0, 69.6, -6, "[1985, 3, 1, 20, 0]", [JEEP % "9"], [], None),
    ("nv_town", 7152, 8915, 1.75, 345, 3, "[1985, 2, 27, 22, 0]", [FIRE, NV_ON], [NV_OFF], ["classic", "remastered"]),
    ("nv_road", 6891.9, 8835.4, 3.0, 69.6, -6, "[1985, 3, 17, 23, 0]", [JEEP % "9", NV_ON], [NV_OFF], ["classic", "remastered"]),
    ("dusk_town", 7152, 8915, 1.75, 345, 3, "[1985, 7, 5, 19, 35]", [FIRE], [], ["classic", "remastered"]),
]

HEADER = '''// GENERATED by gen.py - research only (night-bright bug).
#include "capture_lib.sqf"

triSimUntil { alive player }

capWorld = "Abel"
capFov = 0.7
capSimT = 0
capPinTime = false
capUseView = false
capProps = []
capView = "setup"
capModeName = "none"
capLit = "none"
capGpu = "none"
capPerf = "none"
capFire = objNull
capJeep = objNull
capDrv = objNull

triCaptureAtPresent true
triSetMsaa 4
triSetRenderScale 1.5
showCinemaBorder false
enableRadio false
player setCaptive true
player allowDamage false

createCenter west
createCenter east
capGrpW = createGroup west
capProbe = "HeliHEmpty" createVehicle [7300, 10900, 0]
capCam = "camera" camCreate [7300, 10900, 2]
capCam cameraEffect ["internal", "back"]

capModeV = {
    capModeName = _this select 0;
    capLit = "OK";
    { capR = triSetLighting _x; if (capR != "OK") then { capLit = capR } } forEach (_this select 1);
    capGpuOff = triGpuTimes false;
    capGpuOn = triGpuTimes true;
    capPerfRes = triPerfReset 0;
    format ["view=%1;event=mode;mode=%2;lit=%3;set=%4", capView, capModeName, capLit, _this select 1] call capLog;
}
capFireOn = { if (not (isNull capFire)) then { capFire inflame true } }

triSimFrames 240
call { "view=setup;event=setup;world=Abel;msaa=4;scale=1.5;window=960x640;capture=present" call capLog }
'''


def sq(items):
    return "[" + ", ".join('"%s"' % i for i in items) + "]"


def main():
    name = sys.argv[1]
    modes = sys.argv[2].split(",")
    only = sys.argv[3].split(",") if len(sys.argv) > 3 else None
    out = [HEADER]
    for vi, (vid, x, z, eye, h, p, date, setup, teardown, override) in enumerate(VIEWS):
        if only and vid not in only:
            continue
        vm = [m for m in modes if (override is None or m in override)]
        out.append("\n// ---- %s" % vid)
        out.append('["%s", %s, %s, %s, %s, %s, %s, 0, 0, 800] call capBegin' % (vid, x, z, eye, h, p, date))
        out.extend(setup)
        # The first view also waits out the lamps switching on after the jump to night.
        out.append("triSimFrames %d" % (450 if vi == 0 else 150))
        for m in vm:
            out.append('["%s", %s] call capModeV' % (m, sq(MODES[m])))
            out.append("triSimFrames 90")
            out.append("[] call capReadTimers")
            out.append("[] call capPin")
            out.append("[] call capFireOn")
            out.append("triSimFrames 3")
            out.append('triScreenshot "%s__%s"' % (vid, m))
            out.append('"%s__%s" call capRecord' % (vid, m))
        out.extend(teardown)
        out.append('call { if (not (isNull capDrv)) then { deleteVehicle capDrv; capDrv = objNull } }')
        out.append("[] call capClear")
    out.append('\ncall { "view=done;event=done" call capLog }')
    out.append("triEndTest\n")
    (HERE / (name + ".test.sqf")).write_text("\n".join(out), newline="\n")
    (HERE / (name + ".test.toml")).write_text(
        '# Research-only (git-excluded): night-bright bug views.\n'
        'binary = "PoseidonGame"\n'
        'mission = "tests/rendering/captures/missions/udcap_abel.Abel"\n'
        'tags = ["lighting_capture", "headful", "exclusive"]\n'
        'timeout = 900\n'
        'assert_timeout = 180\n'
        'extra_args = ["--no-strict", "--display-mode", "windowed", "--width", "960", "--height", "640"]\n',
        newline="\n")


if __name__ == "__main__":
    main()
