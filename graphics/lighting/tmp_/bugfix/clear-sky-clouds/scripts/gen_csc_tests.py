"""Generate the clear-sky-clouds research capture tests (git-excluded folder)."""
import pathlib
import sys

OUT = pathlib.Path(sys.argv[1])

HEADER = """// GENERATED by gen_csc_tests.py - clear-sky-clouds bug fix evidence, research only.
#include "csc_lib.sqf"

triSimUntil {{ alive player }}

capWorld = "{world}"
capFov = 0.7
capSimT = 0
capPinTime = false
capUseView = false
capProps = []
capView = "setup"
capModeName = "none"
capLit = "none"
capGpu = "none"
capPerf = "none"

triCaptureAtPresent true
triSetMsaa 4
triSetRenderScale 1.5
showCinemaBorder false
enableRadio false
player setCaptive true
player allowDamage false

createCenter west
createCenter east
capGrpW = createGroup west
capProbe = "HeliHEmpty" createVehicle [{x}, {z}, 0]
capCam = "camera" camCreate [{x}, {z}, 2]
capCam cameraEffect ["internal", "back"]

triSimFrames 240
call {{ "view=setup;event=setup;world={world};msaa=4;scale=1.5;window=960x640;capture=present;run=csc" call capLog }}
"""

TOML = """binary = "PoseidonGame"
mission = "tests/rendering/captures/missions/{mission}"
tags = ["lighting_capture", "headful", "exclusive"]
timeout = 900
assert_timeout = 180
extra_args = ["--no-strict", "--display-mode", "windowed", "--width", "960", "--height", "640"]
"""

DBG1 = ("dbg1", ["debug=1", "post=0"])
DBG1CS0 = ("dbg1cs0", ["debug=1", "post=0", "cloudShadows=0"])
CS0 = ("cs0", ["cloudShadows=0"])


def shot(view, label):
    return f"""[] call capPin
triSimFrames 3
triScreenshot "{view}__{label}"
"{view}__{label}" call capRecord
"""


def view_block(v):
    name, args, shots = v
    s = f"// ---- {name}\n[\"{name}\", {args}] call capBegin\ntriSimFrames 150\n"
    for sh in shots:
        if sh == "classic":
            s += '"classic" call capMode\ntriSimFrames 90\n[] call capReadTimers\n' + shot(name, "classic")
        elif sh == "remastered":
            s += '"remastered" call capMode\ncall { [] call capResetTuning }\ntriSimFrames 90\n[] call capReadTimers\n' + shot(name, "remastered")
        else:
            label, knobs = sh
            ks = ", ".join(f'"{k}"' for k in knobs)
            s += f'call {{ ["{label}", [{ks}]] call capVariant }}\ntriSimFrames 8\n' + shot(name, label)
    s += "call { [] call capResetTuning }\n[] call capClear\n\n"
    return s


abel = [
    # High vantage over the middle of Malden at noon, clear sky: about 25 km2
    # of ground in view, so a 4% cloud cover shows several shadow patches.
    ("clear_high_n", "6000, 5200, 700, 0, -32, [1985, 7, 5, 12, 30], 0, 0, 6000",
     ["remastered", DBG1, DBG1CS0]),
    ("clear_high_s", "6000, 11000, 700, 180, -32, [1985, 7, 5, 12, 30], 0, 0, 6000",
     ["remastered", DBG1, DBG1CS0]),
    # Eye level, the shade track's views where the clear-sky shadow was found.
    ("forest_edge_noon", "4674, 10156, 1.75, 75, 3, [1985, 7, 5, 12, 30], 0, 0, 1500",
     ["classic", "remastered", DBG1, DBG1CS0, CS0]),
    ("coastline_sunset", "1550, 5150, 3, 278, -4, [1985, 7, 5, 18, 35], 0, 0, 4000",
     ["classic", "remastered", DBG1, DBG1CS0, CS0]),
    # Light cloud (overcast 0.1, cover 0.09): the fade-in end of the ramp.
    ("light_high_n", "6000, 5200, 700, 0, -32, [1985, 7, 5, 12, 30], 0.1, 0, 6000",
     ["remastered", DBG1, DBG1CS0]),
]

eden = [
    # Broken cloud (overcast 0.5): unchanged above the clear end.
    ("broken_high", "9200, 3700, 250, 288, -12, [1985, 7, 5, 14, 30], 0.5, 0, 5000",
     ["classic", "remastered", DBG1, DBG1CS0]),
    ("overcast_broken", "9200, 3700, 1.75, 288, -4, [1985, 7, 5, 14, 30], 0.5, 0, 3500",
     ["classic", "remastered", DBG1]),
    ("overcast_heavy", "9200, 3700, 1.75, 288, -4, [1985, 7, 5, 14, 30], 0.9, 0, 3500",
     ["classic", "remastered", DBG1]),
]

for fname, world, x, z, mission, views in (
    ("csc_abel", "Abel", 6000, 5200, "udcap_abel.Abel", abel),
    ("csc_eden", "Eden", 9200, 3700, "udcap_eden.Eden", eden),
):
    body = HEADER.format(world=world, x=x, z=z) + "".join(view_block(v) for v in views)
    body += 'call { "view=done;event=done" call capLog }\ntriEndTest\n'
    (OUT / f"{fname}.test.sqf").write_text(body, newline="\n")
    (OUT / f"{fname}.test.toml").write_text(TOML.format(mission=mission), newline="\n")
    print("wrote", fname)
