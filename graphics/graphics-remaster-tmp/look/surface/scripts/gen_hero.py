def q(s):
    return '"' + s + '"'


def header(world, v0, timing):
    w, h, scale = (1920, 1080, 1.0) if timing else (960, 640, 1.5)
    return f"""// look-surface hero captures ({world}). Generated by tmp/look/surface/scripts/gen_hero.py.
#include "capture_lib.sqf"

triSimUntil {{ alive player }}

capWorld = "{world}"
capFov = 0.7
capSimT = 0
capPinTime = false
capUseView = false
capProps = []
capView = "setup"
capModeName = "none"
capLit = "none"
capGpu = "none"
capPerf = "none"
capFire = objNull

triCaptureAtPresent true
triSetMsaa 4
triSetRenderScale {scale}
showCinemaBorder false
enableRadio false
player setCaptive true
player allowDamage false

createCenter west
createCenter east
capGrpW = createGroup west
capProbe = "HeliHEmpty" createVehicle [{v0['x']}, {v0['z']}, 0]
capCam = "camera" camCreate [{v0['x']}, {v0['z']}, 2]
capCam cameraEffect ["internal", "back"]

triSimFrames 240
call {{ "view=setup;event=setup;world={world};msaa=4;scale={scale};window={w}x{h};capture=present" call capLog }}
""", (w, h)


def prop_line(p):
    classes, fwd, right, rel, kind = p
    cl = "[" + ", ".join(q(c) for c in classes) + "]"
    if kind == "fire":
        return (f"    capFire = [{cl}, {fwd}, {right}, {rel}, \"veh\"] call capSpawn;\n"
                "    if (not (isNull capFire)) then { capFire inflame true };")
    return f"    [{cl}, {fwd}, {right}, {rel}, \"{kind}\"] call capSpawn;"


def view_block(v, modes):
    d = v["date"]
    out = [f"// ---- {v['id']}",
           f"[\"{v['id']}\", {v['x']}, {v['z']}, {v['eye']}, {v['h']}, {v['p']}, [{d[0]}, {d[1]}, {d[2]}, {d[3]}, {d[4]}], {v['oc']}, {v['fog']}, {v['vd']}] call capBegin",
           "call { capCloudRes = triPinCloudDrift [1830, 970, 0] }",
           "call {"]
    out += [prop_line(p) for p in v["props"]]
    out.append("}")
    fire = any(p[4] == "fire" for p in v["props"])
    if v.get("tank"):
        out += ["call {",
                "    capUseView = false;",
                "    capCam cameraEffect [\"terminate\", \"back\"];",
                "    capClearRes = triClearView;",
                "    capTankCls = [\"M60\", \"M1Abrams\", \"T72\"] call capPick;",
                "    capTank = objNull;",
                f"    if (capTankCls != \"\") then {{ capTank = capTankCls createVehicle [{v['x']}, {v['z']}, 0] }};",
                "    if (not (isNull capTank)) then {",
                f"        capTank setDir {v['h']};",
                f"        capTank setPos [{v['x']}, {v['z']}, 0];",
                "        capTank allowDamage false;",
                "        player moveInGunner capTank;",
                "    };",
                "}",
                "triSimFrames 60",
                "call { (vehicle player) switchCamera \"INTERNAL\" }",
                "triSimFrames 60"]
    else:
        out.append("triSimFrames 150")
    for suffix, setting in modes:
        label = f"{v['id']}__{suffix}"
        out += [f"{q(setting)} call capMode",
                "triSimFrames 90",
                "[] call capReadTimers",
                "[] call capPin"]
        if fire:
            out.append("call { if (not (isNull capFire)) then { capFire inflame true } }")
        out += ["triSimFrames 3",
                f"triScreenshot {q(label)}",
                f"{q(label)} call capRecord"]
    if v.get("tank"):
        out += ["call { player action [\"getOut\", vehicle player]; if (not (isNull capTank)) then { deleteVehicle capTank } }",
                "triSimFrames 30"]
    out.append("[] call capClear")
    out.append("call { capCloudRes = triPinCloudDrift [] }")
    return "\n".join(out) + "\n"


def toml(world, mission, lobo, n_shots):
    timeout = 900
    extra = '["--no-strict", "--display-mode", "windowed", "--width", "%d", "--height", "%d"]'
    mods = '"--mods-dir", ".", "--mod", "@LoBo", ' if lobo else ""
    return f"""# look-surface hero captures ({world}); a photo generator, run with run-captures.ps1.
binary = "PoseidonGame"
mission = "{mission}"
tags = ["lighting_capture", "headful", "exclusive"]
timeout = {timeout}
assert_timeout = 240
extra_args = ["--no-strict", {mods}"--display-mode", "windowed", "--width", "%W%", "--height", "%H%"]
"""


def write(outdir, name, world, mission, lobo, views, modes, timing):
    sqf, (w, h) = header(world, views[0], timing)
    for v in views:
        sqf += "\n" + view_block(v, modes)
    sqf += '\ncall { "view=done;event=done" call capLog }\ntriEndTest\n'
    (outdir / f"{name}.test.sqf").write_text(sqf, encoding="utf-8", newline="\n")
    t = toml(world, mission, lobo, len(views) * len(modes)).replace("%W%", str(w)).replace("%H%", str(h))
    (outdir / f"{name}.test.toml").write_text(t, encoding="utf-8", newline="\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir")
    ap.add_argument("--modes", nargs="*", default=None, help="suffix=setting (setting may contain commas)")
    ap.add_argument("--views", default="")
    ap.add_argument("--timing", action="store_true")
    ap.add_argument("--prefix", default="look_surface")
    a = ap.parse_args()
    modes = DEFAULT_MODES
    if a.modes:
        modes = [tuple(m.split("=", 1)) for m in a.modes]
    want = set(x for x in a.views.split(",") if x)
    out = Path(a.outdir)
    abel = [v for v in ABEL if not want or v["id"] in want]
    sinai = [v for v in SINAI if not want or v["id"] in want]
    if abel:
        write(out, f"{a.prefix}_abel", "Abel", "tests/rendering/captures/missions/udcap_abel.Abel", False, abel, modes, a.timing)
    if sinai:
        write(out, f"{a.prefix}_sinai", "Sinai", "tests/rendering/captures/missions/udcap_sinai.Sinai", True, sinai, modes,
              a.timing)
    print("abel views", [v["id"] for v in abel], "sinai views", [v["id"] for v in sinai], "modes", modes)


if __name__ == "__main__":
    main()
