"""Write look_probe4_abel.test.sqf/.toml: several lighting modes per view, one game.

python gen_probe_test.py <captures dir> <name> <spec>
spec: a python literal list of (view, modes) where modes is a list of (label, mode string).
"""
import ast
import sys
from pathlib import Path

VIEWS = {
    "town_night_rain": (1, [7152, 8915, 1.75, 345, 3, [1985, 2, 27, 22, 0], 0.9, 0, 800], 2000),
    "seam_b": (1, [7152, 8915, 1.75, 20, -2, [1985, 2, 27, 22, 0], 0.9, 0, 800], 2600),
    "seam_d": (1, [7160, 8905, 1.75, 10, -6, [1985, 2, 27, 22, 0], 0.9, 0, 800], 3200),
    "seam_day": (1, [7152, 8915, 1.75, 345, 3, [1985, 7, 5, 11, 0], 1, 0, 800], 3800),
}

HEAD = """// puddle agent 4 probes. Generated by gen_probe_test.py.
#include "capture_lib.sqf"

triSimUntil { alive player }

capWorld = "Abel"
capFov = 0.7
capSimT = 0
capPinTime = false
capUseView = false
capProps = []
capView = "setup"
capModeName = "none"
capLit = "none"
capGpu = "none"
capPerf = "none"
capFire = objNull
capBurnV = objNull
capJeep = objNull
capDrv = objNull

call { format ["view=setup;event=window_boot;size=%1", triGetWindowSize] call capLog }
triCaptureAtPresent true
triSetMsaa 4
triSetRenderScale 1.0
showCinemaBorder false
enableRadio false
player setCaptive true
player allowDamage false

createCenter west
createCenter east
capGrpW = createGroup west
capGrpE = createGroup east
capProbe = "HeliHEmpty" createVehicle [7152, 8915, 0]
capCam = "camera" camCreate [7152, 8915, 2]
capCam cameraEffect ["internal", "back"]

triSimFrames 240
call { format ["view=setup;event=setup;world=Abel;msaa=4;scale=1.0;window=%1;capture=present;lobo=%2", triGetWindowSize, "LoBo_camnet" call capHas] call capLog }
"""


def sqf_list(v):
    return "[" + ", ".join(sqf_list(x) if isinstance(x, list) else str(x) for x in v) + "]"


def view_block(view, modes):
    rain, args, simT = VIEWS[view]
    s = [f"\n// ---- {view}", f"call {{ capRain = {rain}; capEyeAbs = false }}",
         f'["{view}", {", ".join(sqf_list(a) if isinstance(a, list) else str(a) for a in args)}] call capBegin',
         f'call {{ capSimT = {simT}; capSimRes = triSetSimTime capSimT; format ["view=%1;event=clock;simT=%2;res=%3", capView, capSimT, capSimRes] call capLog }}',
         'call { capDriftRes = triPinCloudDrift [1830, 970, 0]; format ["view=%1;event=clouds;drift=%2", capView, capDriftRes] call capLog }',
         'call {\n    capFire = [["Fire"], 9, 3, 0, "veh"] call capSpawn;\n    if (not (isNull capFire)) then { capFire inflame true };\n}',
         "triSimFrames 150"]
    for i, (label, mode) in enumerate(modes):
        s += [f'"{mode}" call capMode', "triSimFrames 90" if i == 0 else "triSimFrames 60", "[] call capReadTimers",
              "[] call capPin", "call { if (not (isNull capFire)) then { capFire inflame true } }", "triSimFrames 3",
              f'triScreenshot "{view}__{label}"', f'"{view}__{label}" call capRecord']
    s += ["[] call capClear", "call { capDriftRes = triPinCloudDrift [] }"]
    return "\n".join(s) + "\n"


def main():
    cap = Path(sys.argv[1])
    name = sys.argv[2]
    spec = ast.literal_eval(Path(sys.argv[3]).read_text())
    body = HEAD + "".join(view_block(v, m) for v, m in spec) + '\ncall { "view=done;event=done" call capLog }\ntriEndTest\n'
    (cap / f"{name}.test.sqf").write_text(body, encoding="utf-8", newline="\n")
    toml = (cap / "look_shine_abel.test.toml").read_text(encoding="utf-8")
    (cap / f"{name}.test.toml").write_text(toml, encoding="utf-8", newline="\n")
    print(cap / f"{name}.test.sqf")


if __name__ == "__main__":
    main()
