#!/usr/bin/env python
"""Head-wobble minimal repro: writes one probe test for each build.

The scene mirrors the v2 clips' per-frame loop exactly (capClockAt, capPathAt,
capPropsAt, triSimFrames <sim>, triScreenshot) with a FIXED camera on Malden
(Abel, the checkpoint road, 11:00 clear) and four men in view, heads large:

  A  SoldierEB  SAFE    (default posed man)   7 m ahead, 3 m left
  B  SoldierEB  AWARE   (weapon raised)        9 m ahead, 1 m left
  C  Civilian   SAFE    (civilian group)       8 m ahead, 1.2 m right
  D  SoldierEB  SAFE    the clips' distance    22 m ahead, 8 m right

All four face the camera (dir 180 relative to the view, as the clips pose
them). The men are in the global array capHeads (A, B, C, D), so a variant can
apply a fix to every man in one line.

After the clip the men are deleted and one extra frame, "plate", is shot from
the same camera at the same pinned clock: metric.py subtracts it to find each
man's silhouette and head automatically.

Usage:
  python gen_repro.py --agent 8 --name base
      -> video-work/.../video/look_probe_head8_base.test.sqf (+ .toml)   (overhaul)
      -> vanilla-upstream/.../video/van_probe_head8_base.test.sqf (+ .toml) (vanilla)
  Knobs for fix variants (SQF text, inserted verbatim as top-level statements;
  wrap anything multi-statement in `call { ... }`):
    --setup "<sqf>"      once, after the men are spawned and posed (before the settle)
    --preclip "<sqf>"    once, right before frame 0 (after capMode and capPin)
    --perframe "<sqf>"   every frame, after capPropsAt, before triSimFrames
    --sim N              sim frames per video frame (default 2, as the clips)
    --frames N           video frames (default 120)
    --side ud|van|both   (default both)
  Overhaul-only knobs (vanilla lacks the verb) go in --ud-setup/--ud-preclip/--ud-perframe.
  --ud-step / --van-step "<sqf>" REPLACE each frame's  triSimFrames <sim>  on that side;
  --van-preclip is the vanilla-only twin of --ud-preclip. The plate always runs at setAccTime 1.
"""
import argparse
import os

VIDEO_UD = r"D:\Arma_CWA_worktrees\video-work\arma_CWR\tests\rendering\captures\video"
VIDEO_VAN = r"D:\Arma_CWA_worktrees\vanilla-upstream\tests\rendering\captures\video"

X, Z, H = 7266.4, 8355.9, 200
DATE = "[1985, 7, 5, 11, 0]"

TOML = """# Head-wobble repro ({desc}): {frames} frames at 60 fps, fixed camera. tmp/video/heads/repro/gen_repro.py
# Generated probe, not a regression test: run it with run-captures.ps1.
binary = "PoseidonGame"
mission = "tests/rendering/captures/missions/udcap_abel.Abel"
tags = ["lighting_capture", "headful", "exclusive"]
timeout = 1800
assert_timeout = 180
extra_args = ["--no-strict", "--display-mode", "windowed", "--width", "1920", "--height", "1080"]
"""


def header(side, desc):
    lines = [
        f"// Head-wobble repro ({desc}). Generated by tmp/video/heads/repro/gen_repro.py, do not edit.",
        '#include "../capture_lib.sqf"',
        '#include "capture_motion.sqf"',
        "",
        "triSimUntil { alive player }",
        "",
        'capWorld = "Abel"',
        "capFov = 0.7",
        "capSimT = 0",
        "capPinTime = false",
        "capUseView = false",
        "capProps = []",
        'capView = "setup"',
        'capModeName = "none"',
        'capLit = "none"',
        'capGpu = "none"',
        'capPerf = "none"',
        "capFire = objNull",
        "capHeads = []",
        "",
        'call { format ["view=setup;event=window_boot;size=%1", triGetWindowSize] call capLog }',
    ]
    if side == "ud":
        lines.append("triCaptureAtPresent true")
    else:
        lines.append("// (vanilla: no triCaptureAtPresent)")
    lines += [
        "triSetMsaa 4",
        "triSetRenderScale 1.0",
        "showCinemaBorder false",
        "enableRadio false",
        "player setCaptive true",
        "player allowDamage false",
        "",
        "createCenter west",
        "createCenter east",
        "createCenter civilian",
        "capGrpW = createGroup west",
        "capGrpE = createGroup east",
        "capGrpC = createGroup civilian",
        f'capProbe = "HeliHEmpty" createVehicle [{X}, {Z}, 0]',
        f'capCam = "camera" camCreate [{X}, {Z}, 2]',
        'capCam cameraEffect ["internal", "back"]',
        "",
        "triSimFrames 120",
        "triSimFrames 120",
        "capFps = 60",
        "capPose = {",
        "    if (not (isNull (_this select 0))) then { (_this select 0) setUnitPos (_this select 1); (_this select 0) setBehaviour (_this select 2) };",
        "}",
        "",
    ]
    return lines


def build(side, a):
    desc = f"agent {a.agent} {a.name}, {'overhaul' if side == 'ud' else 'vanilla'}"
    L = header(side, desc)
    view = f"heads{a.agent}_{a.name}"
    L += [
        "call { capRain = 0; capEyeAbs = false }",
        f'["{view}", {X}, {Z}, 1.7, {H}, 0, {DATE}, 0, 0, 1500] call capBegin',
        'call { capSimT = 2000; capSimRes = triSetSimTime capSimT; format ["view=%1;event=clock;simT=%2;res=%3", capView, capSimT, capSimRes] call capLog }',
    ]
    if side == "ud":
        L.append('call { capDriftRes = triPinCloudDrift [1830, 970, 0]; format ["view=%1;event=clouds;drift=%2", capView, capDriftRes] call capLog }')
    L += [
        "call {",
        '    capU = [["SoldierEB"], 7, -3, 180, "man", capGrpE] call capSpawn; capHeads = capHeads + [capU];',
        '    capU = [["SoldierEB"], 9, -1, 180, "man", capGrpE] call capSpawn; capHeads = capHeads + [capU];',
        '    [capU, "UP", "AWARE"] call capPose;',
        '    capU = [["Civilian", "Civilian2"], 8, 1.2, 180, "man", capGrpC] call capSpawn; capHeads = capHeads + [capU];',
        '    capU = [["SoldierEB"], 22, 8, 180, "man", capGrpE] call capSpawn; capHeads = capHeads + [capU];',
        "}",
        "[] call capStageSave",
        "call { capMovers = [] }",
        f"call {{ capPathKind = \"line\"; capPathA = [{X}, {Z}, 1.7, {H}, 0]; capPathB = [{X}, {Z}, 1.7, {H}, 0]; capN = {a.frames}; capLapse = 0 }}",
    ]
    setup = list(a.setup) + (list(a.ud_setup) if side == "ud" else [])
    L += setup
    if side == "ud":
        L += ["call { capSettleArgs = [150, 30, 2] }"] + ["triSimFrames 90"] * 4 + ['"remastered" call capMode']
    else:
        L += ["call { capSettleFrames = 90 }"] + ["triSimFrames 90"] * 6 + ['"vanilla" call capMode']
    L.append("[] call capPin")
    L += list(a.preclip) + (list(a.ud_preclip) if side == "ud" else list(a.van_preclip))
    tag = "ud" if side == "ud" else "vanilla"
    per = list(a.perframe) + (list(a.ud_perframe) if side == "ud" else [])
    for k in range(a.frames):
        lab = f"{view}__{tag}__f{k + 1:04d}"
        L += [f"[{k}] call capClockAt", f"[{k}, {a.frames}] call capPathAt", f"[{k}] call capPropsAt"]
        L += per
        step = list(a.ud_step if side == "ud" else a.van_step) or [f"triSimFrames {a.sim}"]
        L += step + [f'triScreenshot "{lab}"', f'["{lab}", {k}] call capFrameLog']
    # the empty plate: same camera, same pinned clock, no men
    L += [
        "call { setAccTime 1 }",
        "call { { if (not (isNull _x)) then { deleteVehicle _x } } forEach capHeads }",
        f"[{a.frames - 1}] call capClockAt",
        f"[{a.frames - 1}, {a.frames}] call capPathAt",
        f"triSimFrames {a.sim}",
        f"triSimFrames {a.sim}",
        f'triScreenshot "{view}__{tag}__plate"',
        'call { format ["view=%1;event=done", capView] call capLog }',
        "triEndTest",
        "",
    ]
    return desc, "\n".join(L)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--agent", default="8")
    p.add_argument("--name", default="base")
    p.add_argument("--frames", type=int, default=120)
    p.add_argument("--sim", type=int, default=2)
    p.add_argument("--side", choices=["ud", "van", "both"], default="both")
    for k in ("setup", "preclip", "perframe", "ud-setup", "ud-preclip", "ud-perframe", "ud-step", "van-step", "van-preclip"):
        p.add_argument("--" + k, action="append", default=[])
    a = p.parse_args()
    sides = ["ud", "van"] if a.side == "both" else [a.side]
    for side in sides:
        desc, text = build(side, a)
        if side == "ud":
            base = os.path.join(VIDEO_UD, f"look_probe_head{a.agent}_{a.name}")
        else:
            base = os.path.join(VIDEO_VAN, f"van_probe_head{a.agent}_{a.name}")
        with open(base + ".test.sqf", "w", newline="\n") as f:
            f.write(text)
        with open(base + ".test.toml", "w", newline="\n") as f:
            f.write(TOML.format(desc=desc, frames=a.frames))
        print(base + ".test.sqf")


if __name__ == "__main__":
    main()
