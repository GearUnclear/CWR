"""Writes the finals photo tests, finals_a.test.{sqf,toml} and finals_d.test.{sqf,toml}, from one shot table.

  python gen_finals_tests.py

Both tests are the same script with the same cameras; the only differences are the mod folder each one
mounts (tmp\\@kj_final_a or tmp\\@kj_final_d, IN PLACE OF @uddedushka) and where each model's toes are,
so that "4 m in front of the toes" is the same camera rule on both bodies. Site, props and method are
the pipeline's (experiments/kaiju/dedushka_photo.test.sqf): Morton shelf on Everon, the creature at
[5055, 3870] facing south over the bay, an empty T-80, soldiers without weapons, the town's own houses
and church. Nobody fires. 1920 x 1080, the player's lens (0.7) unless a shot says zoom.

Toe tips come from foot_points.py on each built P3D (file space: x = his left, z = back). Facing south,
his left is east and his back is north, so a file point (x, z) is (east, north) of his position.
"""
