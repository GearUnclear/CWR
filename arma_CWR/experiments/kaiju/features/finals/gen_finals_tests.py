def shots_all(toe_r, toe_l):
    """The second pass as ONE run per model: the first table without the five cameras that a tree, a
    house wall or the bank spoiled, the foot frame re-aimed for the moved soldier, then the extra views,
    grouped by time of day."""
    spoiled = ("d06_", "d08_", "d10_", "d11_", "n05_", "n06_")
    first = [i for i in shots(toe_r, toe_l) if not (i[0] == "shot" and i[1].startswith(spoiled))]
    for k, i in enumerate(first):
        if i[0] == "shot" and i[1].startswith("f01_"):
            first[k] = ("shot", i[1], [toe_r[0] + 2.5, toe_r[1] - 9, 1.7, toe_r[0] + 2.5, toe_r[1] + 2, 2.5], i[3])
    second = shots2(toe_r, toe_l)
    cut1 = next(k for k, i in enumerate(first) if i[0] == "date")              # 16:30 starts here
    cut1n = next(k for k, i in enumerate(first) if i[0] == "date" and i[1] == 23)
    cut2 = next(k for k, i in enumerate(second) if i[0] == "date")
    again = [("shot", "n02c_night_300m_last", [0, -300, 1.7, 0, 0, 20], 30)]
    return first[:cut1] + second[:cut2] + first[cut1:cut1n] + first[cut1n:] + second[cut2 + 1:] + again


def write(letter, suffix="", table=None):
    table = table or shots
    mod, toe_r, toe_l = MODELS[letter]
    # The second soldier. First pass: 2 m inside the right toe tip and 1.5 m in front of it. On D that
    # spot is inside the statue's right leg collision box (a box from the bounding box, 7.5 m deep),
    # and the engine pushed the 20 000 t creature 10.6 m off its mark to make room (run d_photo1).
    # Second pass: 1.2 m right of the centre line, 1 m in front of the right toe tip, clear of the box.
    if suffix:
        man2 = (5055 - 1.2, 3870 + toe_r[1] - 1.0)
    else:
        man2 = (5055 + toe_r[0] + 2.0, 3870 + toe_r[1] - 1.5)
    fmt = {"LETTER": letter.upper(), "letter": letter, "MOD": mod, "MAN2E": round(man2[0], 2), "MAN2N": round(man2[1], 2)}
    lines = [HEAD.format(**fmt)]
    for item in table(toe_r, toe_l):
        if item[0] == "shot":
            _k, label, v, settle = item
            lines.append("triSetView ([%s] call dpRel)\ntriSimFrames %d\ntriScreenshot \"%s\"\n\"%s\" call dpNote\n"
                         % (", ".join("%g" % x for x in v), settle, label, label))
        elif item[0] == "date":
            _k, hh, mm, frames = item
            lines.append("setDate [1985, 6, 10, %d, %d]\ntriSimFrames %d\n" % (hh, mm, frames))
            if suffix and hh >= 22:
                # Run a_photo2: the first six night frames, up to 8.6 s of game time after the jump to
                # 23:30, came out near black (fullbright faces included); from 9.4 s on they were right.
                # Runs a_photo1 and d_photo1 were right from 6.1 s. So wait on the clock, not on frames.
                lines.append("dpT0 = time\ntriSimUntil { time > dpT0 + 15 }\ntriSimFrames 30\n")
        elif item[0] == "fov":
            lines.append("%g call dpFov\n" % item[1])
    lines.append(TAIL)
    base = os.path.join(HERE, "finals_%s%s.test" % (letter, suffix))
    with open(base + ".sqf", "w", encoding="utf-8", newline="\n") as fh:
        fh.write("".join(lines))
    with open(base + ".toml", "w", encoding="utf-8", newline="\n") as fh:
        fh.write(TOML.format(**fmt))
    n = sum(1 for i in table(toe_r, toe_l) if i[0] == "shot")
    print("wrote %s.sqf and .toml (%d shots, mod %s)" % (base, n, mod))


for letter in MODELS:
    write(letter)
    write(letter, "2", shots_all)
