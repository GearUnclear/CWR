"""Writes the finals motion tests, finals_a_anim.test.{sqf,toml} and finals_d_anim.test.{sqf,toml}.

  python gen_finals_anim_tests.py

The boned candidate (tmp\\@kj_final_<letter>_anim, built by build-final.ps1 -Skin bones and
build-final-anim.ps1) stands on the flat Everon airfield, the anim feature's site, idles through one
12 s loop and is then walked east by the AI (doMove to a far goal, so the walk runs at its full rate).
Bursts of frames every half second from cameras that travel with him: side, front quarter, legs close,
behind, head on, and one fixed camera at a man's eye height that he walks past. FINW lines in
game_stdout.log give time, move, position and heading for every frame. Nobody is armed, nobody fires.
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MODS = {"a": "@kj_final_a_anim", "d": "@kj_final_d_anim"}

TOML = '''# Dedushka finals motion test, candidate {LETTER} (experiment, kept out of tests/integration so a sweep
# never runs it). Generated by gen_finals_anim_tests.py. It mounts <git root>/tmp/{MOD}, built by
# features/finals/build-final-anim.ps1 -Letter {letter}, IN PLACE OF @uddedushka. Run it through
# experiments/kaiju/run-tri.ps1 (features/finals/run-finals.ps1). Quiet, nobody armed, nobody fires.
tags = ["kaiju", "experiment", "visual"]
binary = "PoseidonGame"
mission = "experiments/kaiju/features/finals/FinalsPhoto.Eden"
timeout = 600
assert_timeout = 120
extra_args = ["--nosound", "--no-strict", "--width", "1920", "--height", "1080", "--mods-dir", "..", "--mod", "{MOD}"]
'''

HEAD = '''// ============================================================================
//  Dedushka finals motion test, candidate {LETTER}: idle, then a walk east along the airfield.
//  GENERATED by gen_finals_anim_tests.py: edit that, not this file.
//  Needs tmp\\{MOD}. Quiet: nobody is armed, nobody fires, --nosound.
// ============================================================================
triSimUntil {{ alive player }}
player allowDammage false
player setCaptive true
removeAllWeapons player
player setPos [4700, 10950, 0]
setDate [1985, 6, 10, 12, 0]
0 setOvercast 0.2
0 setFog 0
setViewDistance 2500
showCinemaBorder false
triEnableShadows
faC = createCenter civilian
faG = createGroup civilian
faE = createCenter east
faEG = createGroup east
ded = objNull
faAt = [4766, 11200, 0]
"UDDedushka" createUnit [faAt, faG, "ded = this", 0.5, "PRIVATE"]
triSimFrames 5
triAssert [!(isNull ded)]
triAssertEq [typeOf ded, "UDDedushka"]
faAnim = 0
ded addEventHandler ["AnimChanged", {{ faAnim = faAnim + 1; logInfo format ["FINA anim %1 %2", time, _this select 1] }}]
faHold = {{ ded setCaptive true; ded disableAI "MOVE"; ded disableAI "TARGET"; ded disableAI "AUTOTARGET"; faG setBehaviour "CARELESS"; ded setUnitPos "UP"; ded stop true; ded setDir 90; ded setPos faAt }}
call faHold
ded allowDammage false
// Scale props beside the track: an empty T-80 and a soldier without a weapon.
faTank = "T80" createVehicle [4800, 11172, 0]
faTank setDir 90
faMan = objNull
"SoldierEB" createUnit [[4792, 11176, 0], faEG, "faMan = this", 0.5, "PRIVATE"]
triSimFrames 5
if (true) then {{ removeAllWeapons faMan; faMan setCaptive true; faMan disableAI "MOVE"; faMan disableAI "TARGET"; faMan disableAI "AUTOTARGET"; faMan setCombatMode "BLUE"; faMan setBehaviour "CARELESS"; faMan stop true; faMan setDir 0 }}
faProbe = "HeliHEmpty" createVehicle [4800, 11500, 0]
faCam = "camera" camCreate [4800, 10850, 30]
faCam cameraEffect ["internal", "back"]
faFov = {{ faCam camSetTarget [4800, 11200, 30]; faCam camSetFov _this; faCam camCommit 0 }}
0.7 call faFov
// faRel: [camera east, camera north, eye height above the local ground, aim height above his feet],
// relative to where he is NOW, so the camera travels with him.
faRel = {{ private ["_p", "_cx", "_cz", "_g", "_e"]; _p = getPosASL ded; _cx = (_p select 0) + (_this select 0); _cz = (_p select 1) + (_this select 1); faProbe setPos [_cx, _cz, 0]; _g = (getPosASL faProbe) select 2; _e = _g + (_this select 2); [_cx, _e, _cz, (_p select 0) - _cx, (_p select 2) + (_this select 3) - _e, (_p select 1) - _cz] }}
// faFix: a camera that stays where faFixAt = [x, eye ASL, z] says and turns to follow him.
faFix = {{ private ["_p"]; _p = getPosASL ded; [faFixAt select 0, faFixAt select 1, faFixAt select 2, (_p select 0) - (faFixAt select 0), (_p select 2) + _this - (faFixAt select 1), (_p select 1) - (faFixAt select 2)] }}
faNote = {{ logInfo format ["FINW %1 t %2 move %3 pos %4 dir %5 speed %6 animChanges %7", _this, time, getMove ded, getPosASL ded, getDir ded, speed ded, faAnim] }}
triSimFrames 200
logInfo format ["FINW placed: asl %1 dir %2 move %3 alive %4", getPosASL ded, getDir ded, getMove ded, alive ded]
triAssertEq [getMove ded, "dedidle"]
triSetView ([57, -40, 1.7, 20] call faRel)
triSimFrames 30
triScreenshot "00_warmup_discard"
faT0 = time
'''

TAIL = '''faMoved = ((getPosASL ded) select 0) - 4766
call faHold
triSimFrames 30
logInfo format ["FINW end: time %1 alive %2 move %3 asl %4 moved %5 m animChanges %6", time, alive ded, getMove ded, getPosASL ded, faMoved, faAnim]
triAssert [alive ded]
triAssert [faMoved > 40]
triEndTest
'''


def polar(bearing, dist):
    return (round(dist * math.sin(math.radians(bearing)), 2), round(dist * math.cos(math.radians(bearing)), 2))


def write(letter):
    mod = MODS[letter]
    fmt = {"LETTER": letter.upper(), "letter": letter, "MOD": mod}
    out = [HEAD.format(**fmt)]

    def rel_shot(t0, t, label, cam, eye, aim):
        out.append("triSimUntil { time >= %s + %g }\ntriSetView ([%g, %g, %g, %g] call faRel)\ntriSimFrames 2\ntriScreenshot \"%s\"\n\"%s\" call faNote\n"
                   % (t0, t, cam[0], cam[1], eye, aim, label, label))

    # He faces east: his front is east, his right is south.
    front_q = polar(125, 70)
    for k, t in enumerate((0.0, 3.0, 6.0, 9.0)):
        rel_shot("faT0", t, "i%02d_idle_front_quarter_t%02d" % (k, int(t)), front_q, 1.7, 20)
    for k, t in enumerate((10.5, 13.5, 16.5, 19.5)):
        rel_shot("faT0", t, "j%02d_idle_side_t%02d" % (k, int(t)), polar(180, 75), 1.7, 20)
    out.append("triAssertEq [getMove ded, \"dedidle\"]\n")
    out.append("if (true) then { faW0 = time; ded stop false; ded enableAI \"MOVE\"; ded doMove [5060, 11200, 0] }\n")
    out.append("logInfo format [\"FINW walk start %1 %2\", time, getPosASL ded]\n")
    n = 0
    t = 0.5
    # the start of the walk, from the side
    while t <= 2.5:
        rel_shot("faW0", t, "w%03d_start_side" % n, polar(180, 75), 1.7, 18)
        n += 1
        t += 0.5
    while t <= 10.0:
        rel_shot("faW0", t, "w%03d_side" % n, polar(180, 75), 1.7, 18)
        n += 1
        t += 0.5
    out.append("triAssertEq [getMove ded, \"dedwalk\"]\n")
    while t <= 17.5:
        rel_shot("faW0", t, "w%03d_front_quarter" % n, polar(125, 80), 1.7, 18)
        n += 1
        t += 0.5
    while t <= 25.0:
        rel_shot("faW0", t, "w%03d_legs_side_40m" % n, polar(180, 40), 1.7, 9)
        n += 1
        t += 0.5
    while t <= 29.0:
        rel_shot("faW0", t, "w%03d_behind" % n, polar(290, 75), 1.7, 18)
        n += 1
        t += 0.5
    while t <= 33.0:
        rel_shot("faW0", t, "w%03d_head_on" % n, polar(90, 90), 1.7, 18)
        n += 1
        t += 0.5
    # a man standing 30 m ahead of him and 14 m south of the track, watching him pass
    out.append("triSimUntil { time >= faW0 + 33.5 }\n")
    out.append("if (true) then { faP = getPosASL ded; faProbe setPos [(faP select 0) + 30, (faP select 1) - 14, 0]; faFixAt = [(faP select 0) + 30, ((getPosASL faProbe) select 2) + 1.7, (faP select 1) - 14] }\n")
    while t <= 46.0:
        out.append("triSimUntil { time >= faW0 + %g }\ntriSetView (15 call faFix)\ntriSimFrames 2\ntriScreenshot \"w%03d_passing_a_man\"\n\"w%03d_passing_a_man\" call faNote\n"
                   % (t, n, n))
        n += 1
        t += 0.5
    out.append(TAIL)
    base = os.path.join(HERE, "finals_%s_anim.test" % letter)
    with open(base + ".sqf", "w", encoding="utf-8", newline="\n") as fh:
        fh.write("".join(out))
    with open(base + ".toml", "w", encoding="utf-8", newline="\n") as fh:
        fh.write(TOML.format(**fmt))
    print("wrote %s.sqf and .toml (%d walk frames, mod %s)" % (base, n, mod))


for letter in MODS:
    write(letter)
