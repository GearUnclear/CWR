# Runs one brain tri test. Copies the script payload into the test mission,
# then hands over to the pipeline's run-tri.ps1 (machine gates, hidden desktop,
# one game, --nosound). Windows PowerShell 5.1 or later.
#
#   powershell -NoProfile -File run-brain.ps1 -Name brain_states [-Tag s1] [-TimeoutSec 600]
#   powershell -NoProfile -File run-brain.ps1 -Name brain_demo -Mission DedDemo.Eden
#   powershell -NoProfile -File run-brain.ps1 -Name brain_demo -Full
#
# -Mission  the mission folder the test's toml names (default DedBrain.Eden).
# -With     other features whose payload (features\<name>\kj\<name>) is copied
#           in beside kj\brain, when that folder exists. The brain runs alone
#           without any of them; with them it calls their entry points.
# -Full     the demo with every other feature that is built: makes
#           DedDemoFull.Eden (a copy of DedDemo.Eden whose addOns[] also name
#           the roar and beam addons) and <Name>_full.test.sqf/.toml (the same
#           test, mounting @kj_roar and @kj_beam as well), copies in every
#           payload, and runs that. The generated files are not sources.
#
# Output: kaiju-notes\features\brain\runs\<tag>-<stamp>\, wrapper log in
# kaiju-notes\features\brain\logs. Needs the mount tmp\@kj_brain
# (build-kj-brain.ps1); the toml of each test names the mods it mounts.
param(
    [Parameter(Mandatory)][string]$Name,
    [string]$Tag = '',
    [string]$Mission = 'DedBrain.Eden',
    [string[]]$With = @(),
    [switch]$Full,
    [int]$TimeoutSec = 600,
    [int]$MaxWaitSec = 7200
)
$ErrorActionPreference = 'Stop'
$here = $PSScriptRoot
$notes = 'D:\Arma_CWA_worktrees\kaiju-notes\features\brain'
if (-not $Tag) { $Tag = $Name }
$gitRoot = [IO.Path]::GetFullPath((Join-Path $here '..\..\..\..\..'))
if (-not (Test-Path -LiteralPath (Join-Path $gitRoot 'tmp\@kj_brain\addons\uddedushka.pbo'))) {
    Write-Host "missing mount: $gitRoot\tmp\@kj_brain (run build-kj-brain.ps1)"; exit 2
}
if ($Full) {
    $mods = '@kj_brain'
    $extra = @()
    if (Test-Path -LiteralPath (Join-Path $gitRoot 'tmp\@kj_roar\addons\kj_roar.pbo')) { $mods += ';@kj_roar'; $extra += 'kj_roar' }
    if (Test-Path -LiteralPath (Join-Path $gitRoot 'tmp\@kj_beam\addons\kjbeam.pbo')) { $mods += ';@kj_beam'; $extra += 'kjbeam' }
    $srcM = Join-Path $here 'DedDemo.Eden'
    $dstM = Join-Path $here 'DedDemoFull.Eden'
    if (Test-Path -LiteralPath $dstM) { Remove-Item -LiteralPath $dstM -Recurse -Force }
    [void][IO.Directory]::CreateDirectory($dstM)
    Get-ChildItem -LiteralPath $srcM -File | Copy-Item -Destination $dstM
    $sqmPath = Join-Path $dstM 'mission.sqm'
    $sqm = [IO.File]::ReadAllText($sqmPath)
    $list = '"uddedushka"'
    foreach ($a in $extra) { $list += ",`r`n`t`t`"$a`"" }
    $sqm = $sqm.Replace('"uddedushka"', $list)
    [IO.File]::WriteAllText($sqmPath, $sqm, (New-Object Text.UTF8Encoding($false)))
    $genName = "${Name}_full"
    Copy-Item -LiteralPath (Join-Path $here "$Name.test.sqf") -Destination (Join-Path $here "$genName.test.sqf") -Force
    $toml = "# GENERATED by run-brain.ps1 -Full from $Name.test.toml. Do not edit, do not keep.`r`n" +
        "tags = [`"kaiju`", `"experiment`", `"brain`"]`r`nbinary = `"PoseidonGame`"`r`n" +
        "mission = `"experiments/kaiju/features/brain/DedDemoFull.Eden`"`r`ntimeout = 900`r`nassert_timeout = 300`r`n" +
        "extra_args = [`"--nosound`", `"--no-strict`", `"--width`", `"1600`", `"--height`", `"900`", `"--mods-dir`", `"..`", `"--mod`", `"$mods`"]`r`n"
    [IO.File]::WriteAllText((Join-Path $here "$genName.test.toml"), $toml, (New-Object Text.UTF8Encoding($false)))
    Write-Host "full demo: mods $mods, addOns $($extra -join ', ')"
    $Name = $genName
    $Mission = 'DedDemoFull.Eden'
    $With = @('roar', 'crush', 'beam', 'anim')
    if ($Tag -notmatch 'full') { $Tag = "$Tag-full" }
}
$mdir = Join-Path $here $Mission
if (-not (Test-Path -LiteralPath (Join-Path $mdir 'mission.sqm'))) { Write-Host "no mission at $mdir"; exit 2 }
$kj = Join-Path $mdir 'kj'
if (Test-Path -LiteralPath $kj) { Remove-Item -LiteralPath $kj -Recurse -Force }
$dst = Join-Path $kj 'brain'
[void][IO.Directory]::CreateDirectory($dst)
Copy-Item -Path (Join-Path $here 'kj\brain\*') -Destination $dst -Force
foreach ($f in $With) {
    foreach ($one in ($f -split ',')) {
        $one = $one.Trim()
        if (-not $one) { continue }
        $src = Join-Path $here "..\$one\kj\$one"
        if (Test-Path -LiteralPath $src) {
            $d2 = Join-Path $kj $one
            [void][IO.Directory]::CreateDirectory($d2)
            Copy-Item -Path (Join-Path $src '*') -Destination $d2 -Recurse -Force
            Write-Host "payload: kj\$one"
        } else {
            Write-Host "payload kj\$one not there, the brain uses its stub"
        }
    }
}
# Tell the brain what is there, so it does not have to probe for files
# (a probe for a missing file is logged by the engine as a warning).
$has = @('roar\roar.sqs', 'beam\fire.sqs', 'crush\loop.sqs', 'anim\ded_anim_timing.sqf') | ForEach-Object {
    if (Test-Path -LiteralPath (Join-Path $kj $_)) { 'true' } else { 'false' }
}
$haveText = "// Written by run-brain.ps1 for this staged copy: [roar, beam, crush, anim timing table].`r`nKJ_brainHas = [" + ($has -join ', ') + "];`r`n"
[IO.File]::WriteAllText((Join-Path $dst 'have.sqf'), $haveText, (New-Object Text.UTF8Encoding($false)))
Write-Host "features in the mission: roar $($has[0]) beam $($has[1]) crush $($has[2]) anim $($has[3])"
$stamp = Get-Date -Format 'MMdd-HHmmss'
$out = Join-Path $notes "runs\$Tag-$stamp"
$runTri = [IO.Path]::GetFullPath((Join-Path $here '..\..\run-tri.ps1'))
powershell -NoProfile -File $runTri -Test "experiments/kaiju/features/brain/$Name.test.sqf" -Tag $Tag -OutDir $out -LogDir (Join-Path $notes 'logs') -TimeoutSec $TimeoutSec -MaxWaitSec $MaxWaitSec
$code = $LASTEXITCODE
Write-Host "BRAINOUT=$out"
exit $code
